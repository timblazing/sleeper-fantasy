import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const directory = new URL("../src/styles/reference/", import.meta.url);
const baseUrl = "https://components.blasingame.dev/design/";
const files = ["variables.css", "DESIGN.md"];
const hash = (text) => createHash("sha256").update(text).digest("hex");
const mediaTokens = (css) => {
  const dark = css.match(/\.dark\s*\{([^}]+)\}/)?.[1];
  if (!dark) throw new Error("Published variables must contain a dark palette.");
  return `/* Generated by npm run design:sync from the pinned variables.css. */\n:root { color-scheme: light; }\n@media (prefers-color-scheme: dark) {\n  :root {${dark}\n    color-scheme: dark;\n  }\n}\n`;
};

if (process.argv.includes("--update")) {
  // Fetch and validate every artifact before changing the pinned snapshot.
  const artifacts = await Promise.all(files.map(async (file) => {
    const response = await fetch(baseUrl + file, { signal: AbortSignal.timeout(15000) });
    if (!response.ok) throw new Error(`${file}: HTTP ${response.status}`);
    const text = await response.text();
    if (file === "variables.css" && !text.includes("--background:")) throw new Error("Invalid palette");
    if (file === "DESIGN.md" && !text.startsWith("#")) throw new Error("Invalid design reference");
    return { file, text };
  }));
  const css = artifacts.find(({ file }) => file === "variables.css").text;
  const generated = mediaTokens(css);
  for (const { file, text } of artifacts) await writeFile(new URL(file, directory), text);
  await writeFile(new URL("../system-theme.css", directory), generated);
  await writeFile(new URL("source.json", directory), JSON.stringify({
    baseUrl, reviewedAt: new Date().toISOString().slice(0, 10),
    files: Object.fromEntries(artifacts.map(({ file, text }) => [file, { url: baseUrl + file, sha256: hash(text) }])),
    policy: "Pinned published artifacts; review the diff and both themes before committing a refresh.",
  }, null, 2) + "\n");
  console.log("Updated design reference. Review the token diff and /design-system in both themes.");
} else {
  const source = JSON.parse(await readFile(new URL("source.json", directory), "utf8"));
  for (const file of files) {
    const text = await readFile(new URL(file, directory), "utf8");
    if (hash(text) !== source.files[file].sha256) throw new Error(`${file} differs from its pinned hash`);
    if (file === "variables.css") {
      const generated = await readFile(new URL("../system-theme.css", directory), "utf8");
      if (generated !== mediaTokens(text)) throw new Error("System theme differs from the pinned palette");
    }
  }
  console.log(`Design reference verified (${source.reviewedAt}).`);
}
